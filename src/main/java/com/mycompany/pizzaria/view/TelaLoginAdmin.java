    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        String login = jTextField1.getText().trim();
        String senha = new String(jPasswordField1.getPassword());

        if (login.isEmpty() || senha.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha usuario e senha.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (ADMIN_USUARIO.equals(login) && ADMIN_SENHA.equals(senha)) {
            new TelaAdmin().setVisible(true);
            dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Usuario ou senha incorretos.", "Erro", JOptionPane.ERROR_MESSAGE);
            jPasswordField1.setText("");
            jPasswordField1.requestFocus();
        }
    }

